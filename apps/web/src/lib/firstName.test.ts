import { describe, expect, it } from 'vitest';
import { firstName } from './format';

describe('firstName', () => {
  it.each([
    ['Ніконов Вячеслав Євгенович', 'Вячеслав'],
    ['Бабенко Станіслав Миколайович', 'Станіслав'],
    ['Денисюк Наталія Василівна', 'Наталія'],
    ['Ніконов Вячеслав', 'Вячеслав'],
    ['Андрій Вербіцький', 'Андрій'],
    ['Вадим Єлфімов', 'Вадим'],
    ['Ольга Горшкова', 'Ольга'],
    ['Болдирєв Дмитро', 'Дмитро'],
    ['Каленик Ірина', 'Ірина'],
    ['Наконечна Ірина', 'Ірина'],
    ['Швайківська Вікторія', 'Вікторія'],
    ['Слободяник Ігор', 'Ігор'],
    ['Роман Пономаренко', 'Роман'],
    ['Елена Морозова', 'Елена'],
    ['Михаил Волков', 'Михаил'],
    ['Пономаренко Кароліна', 'Кароліна'],
    ['Пономаренко Аделіна', 'Аделіна'],
    ['Харруд Хишам', 'Хишам'],
    ['Анна', 'Анна'],
  ])('%s → %s', (full, expected) => { expect(firstName(full)).toBe(expected); });
});
